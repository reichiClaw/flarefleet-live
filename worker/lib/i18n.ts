const dicts: Record<Language, Dict> = { de, en };

export function t(lang: Language, key: string, params?: Record<string, string | number>): string {
  let s = dicts[lang]?.[key] ?? dicts.en[key] ?? key;
  if (params) for (const [k, v] of Object.entries(params)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

export function pickLanguage(header: string | undefined | null, fallback: Language = "de"): Language {
  if (!header) return fallback;
  const h = header.toLowerCase();
  if (h.startsWith("en")) return "en";
  if (h.startsWith("de")) return "de";
  return fallback;
}
