const dicts: Record<Language, Dict> = { de, en };

export type TFn = (key: string, params?: Record<string, string | number>) => string;

export function translate(lang: Language, key: string, params?: Record<string, string | number>): string {
  let s = dicts[lang][key] ?? dicts.en[key] ?? key;
  if (params) for (const [k, v] of Object.entries(params)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

const I18nContext = createContext<{ lang: Language; t: TFn }>({ lang: "de", t: (k, p) => translate("de", k, p) });

export function I18nProvider({ lang, children }: { lang: Language; children: ReactNode }) {
  const t: TFn = (k, p) => translate(lang, k, p);
  return <I18nContext.Provider value={{ lang, t }}>{children}</I18nContext.Provider>;
}

export function useT() {
  return useContext(I18nContext);
}

export function detectLanguage(): Language {
  const stored = localStorage.getItem("ff_lang");
  if (stored === "de" || stored === "en") return stored;
  return navigator.language.toLowerCase().startsWith("en") ? "en" : "de";
}
